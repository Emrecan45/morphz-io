export const LANGUAGES = [
  { id: 'fr', name: 'Français' },
  { id: 'en', name: 'English' },
  { id: 'es', name: 'Español' },
  { id: 'de', name: 'Deutsch' },
  { id: 'pt', name: 'Português' },
  { id: 'ru', name: 'Русский' },
  { id: 'tr', name: 'Türkçe' },
]

const STORE_KEY = 'morphz.lang'
let currentLang = 'en'

try {
  const kept = localStorage.getItem(STORE_KEY)
  if (STRINGS[kept]) {
    currentLang = kept
  } else if (navigator.language) {
    const nav = navigator.language.slice(0, 2).toLowerCase()
    if (STRINGS[nav]) currentLang = nav
  }
} catch {
}

const listeners = []

export function language() {
  return currentLang
}

export function setLanguage(id) {
  if (!STRINGS[id] || id === currentLang) return
  currentLang = id
  try {
    localStorage.setItem(STORE_KEY, id)
  } catch {
  }
  document.documentElement.lang = id
  for (const fn of listeners) fn(id)
}

export function onLanguage(fn) {
  listeners.push(fn)
}

export function t(key, params) {
  let text = STRINGS[currentLang][key]
  if (text === undefined) text = STRINGS.fr[key]
  if (text === undefined) text = key
  if (params) {
    for (const name of Object.keys(params)) text = text.split('{' + name + '}').join(String(params[name]))
  }
  return text
}

export function creatureName(id, fallbackPt) {
  const v = STRINGS[currentLang]['c_' + id]
  return v === undefined ? fallbackPt || id : v
}

export function creatureRole(id, fallbackPt) {
  const v = STRINGS[currentLang]['r_' + id]
  return v === undefined ? fallbackPt || '' : v
}

document.documentElement.lang = currentLang

